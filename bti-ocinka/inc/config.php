function bti_opt(string $key): string {
    static $opts = null;
    if ($opts === null) {
        $saved = get_option('bti_settings', []);
        $opts  = array_merge(bti_defaults(), is_array($saved) ? array_filter($saved, fn($v) => $v !== '' && $v !== null) : []);
        // секрети можуть бути порожніми навмисно
        foreach (['tg_token', 'tg_chat'] as $k) $opts[$k] = $saved[$k] ?? '';
    }
    return (string)($opts[$key] ?? '');
}

